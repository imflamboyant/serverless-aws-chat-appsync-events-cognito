// Writes client/config.js from the stack outputs
import { writeFileSync } from 'node:fs';
import { stackOutputs } from './outputs.mjs';

const outputs = stackOutputs();
const config = {
    cognitoDomain: outputs.CognitoDomainUrl,
    clientId: outputs.UserPoolClientId,
    redirectUri: 'http://localhost:5173/',
    restApiUrl: outputs.RestApiUrl,
    eventApiHttpDns: outputs.EventApiHttpDns,
    eventApiRealtimeDns: outputs.EventApiRealtimeDns,
};
const file = new URL('../client/config.js', import.meta.url);
writeFileSync(file, `// generated by scripts/write-config.mjs\nwindow.CHAT_CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log('Wrote client/config.js');
